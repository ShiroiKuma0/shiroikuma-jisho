// Generates lib/src/language/implementations/japanese_transforms.g.dart
// from Yomitan's Japanese deinflection rules
// (ext/js/language/ja/japanese-transforms.js), so the app deinflects the
// way current Yomitan does instead of by a hand-ported copy of old
// Yomichan's deinflect.json.
//
//   node tools/gen-japanese-transforms.mjs [yomitan-commit]
//
// Fetches the three source files at that commit (default: master) into a
// temporary directory, imports them, and writes the conditions and rules
// as Dart constants. Re-run to pick up upstream rule changes.

import {mkdtempSync, mkdirSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

const commit = process.argv[2] ?? 'master';
const base = `https://raw.githubusercontent.com/yomidevs/yomitan/${commit}/ext/js`;
const dir = mkdtempSync(join(tmpdir(), 'yomitan-'));
mkdirSync(join(dir, 'language', 'ja'), {recursive: true});
writeFileSync(join(dir, 'package.json'), '{"type": "module"}');

async function fetchTo(path) {
  const res = await fetch(`${base}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  writeFileSync(join(dir, path), await res.text());
}
await fetchTo('language/language-transforms.js');
await fetchTo('language/ja/japanese-transforms.js');

const {japaneseTransforms} = await import(
  pathToFileURL(join(dir, 'language', 'ja', 'japanese-transforms.js')).href);

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
const list = (a) => `[${a.map(q).join(', ')}]`;

let out = `// GENERATED by tools/gen-japanese-transforms.mjs from Yomitan
// ext/js/language/ja/japanese-transforms.js at ${commit}. Do not edit.
// Yomitan is GPL-3.0; these rules are its data.

// ignore_for_file: lines_longer_than_80_chars

part of 'japanese_transformer.dart';

/// Condition name -> (is a dictionary form, sub-conditions).
const Map<String, (bool, List<String>)> _jaConditions = {
`;
for (const [name, c] of Object.entries(japaneseTransforms.conditions)) {
  out += `  ${q(name)}: (${c.isDictionaryForm ? 'true' : 'false'}, ${list(c.subConditions ?? [])}),\n`;
}
out += `};

/// Transform id -> rules (type, inflected, deinflected, conditionsIn,
/// conditionsOut). Type is 's'uffix, 'p'refix or 'w'hole word.
const Map<String, List<(String, String, String, List<String>, List<String>)>> _jaTransforms = {
`;
let ruleCount = 0;
for (const [id, t] of Object.entries(japaneseTransforms.transforms)) {
  out += `  ${q(id)}: [\n`;
  for (const r of t.rules) {
    const src = r.isInflected.source;
    let type, inflected, deinflected;
    if (r.type === 'suffix') {
      type = 's'; inflected = src.replace(/\$$/, ''); deinflected = r.deinflected ?? r.deinflect('');
    } else if (r.type === 'prefix') {
      type = 'p'; inflected = src.replace(/^\^/, ''); deinflected = r.deinflect('');
    } else {
      type = 'w'; inflected = src.replace(/^\^/, '').replace(/\$$/, ''); deinflected = r.deinflect('');
    }
    if (/[\\[\](){}*+?.|^$]/.test(inflected)) throw new Error(`regex in rule ${id}: ${src}`);
    out += `    (${q(type)}, ${q(inflected)}, ${q(deinflected)}, ${list(r.conditionsIn)}, ${list(r.conditionsOut)}),\n`;
    ruleCount++;
  }
  out += `  ],\n`;
}
out += `};\n`;

writeFileSync('lib/src/language/implementations/japanese_transforms.g.dart', out);
console.log(`${Object.keys(japaneseTransforms.transforms).length} transforms, ${ruleCount} rules`);
